export function t(lang, key, vars) {
  const code = lang === 'ta' ? 'ta' : 'en'
  let text = dict[code][key] ?? dict.en[key] ?? key
  if (vars && typeof text === 'string') {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replaceAll(`{${k}}`, String(v))
    })
  }
  return text
}

export function resolveLang(userOrLang) {
  if (userOrLang === 'ta' || userOrLang === 'en') return userOrLang
  return userOrLang?.language === 'ta' ? 'ta' : 'en'
}

export function shockKey(id, part = '') {
  const base = `shock_${String(id).replaceAll('-', '_')}`
  return part ? `${base}_${part}` : base
}

export function buildSpokenNudge(dashboard = {}, lang = 'en') {
  const today = dashboard.income?.today
  const suggested = dashboard.savings?.suggested
  const hasToday = today != null && Number(today) > 0
  const hasSave = suggested != null && Number(suggested) > 0
  const focus = dashboard.settings?.focusAreas || []
  const flags = dashboard.settings?.hardshipFlags || []
  const medical = focus.includes('medical') || flags.includes('medical')
  const loan = focus.includes('loan_risk') || flags.includes('loan_pressure')
  const weather = focus.includes('weather') || flags.includes('weather_disruption')
  const family = focus.includes('family_expense') || flags.includes('family_expense')
  const fuel = focus.includes('fuel') || flags.includes('fuel_cost')
  const shock = focus.includes('income_shock') || flags.includes('no_work')

  if (lang === 'ta') {
    if (medical) {
      return 'மருத்துவ அழுத்தம் குறிக்கப்பட்டுள்ளது. சுகாதாரத் திட்டங்களையும் உறுதிப்படுத்தப்பட்ட ஆதரவையும் பாருங்கள் — புதிய கடன் அல்ல.'
    }
    if (loan) return 'கடன் அழுத்தம் குறிக்கப்பட்டுள்ளது. இந்த வாரம் மற்றொரு கடன் எடுக்காமல் கடன் அடுக்கைப் பாருங்கள்.'
    if (weather) return 'வானிலை இடையூறு குறிக்கப்பட்டுள்ளது. கெட்ட வாரம் சிமுலேட்டரில் உங்கள் பாதுகாப்பு நிதியைச் சோதிக்கவும்.'
    if (shock) return 'வருமான அதிர்ச்சி குறிக்கப்பட்டுள்ளது. வேலை இல்லாத நாட்களுக்கு பையைத் தயார் செய்யுங்கள்.'
    if (family) return 'குடும்பச் செலவு கவனம் இயக்கத்தில் உள்ளது. இலக்குகளைத் திறந்து அதற்கான சேமிப்பைத் தொடங்குங்கள்.'
    if (fuel) return 'எரிபொருள் செலவு அழுத்தம் உள்ளது. செலவுகளைப் பதிவு செய்து சிறிய உபரியைச் சேமியுங்கள்.'
    if (hasToday && hasSave) {
      return `இன்று நீங்கள் ₹${Number(today).toLocaleString('en-IN')} சம்பாதித்துள்ளீர்கள். ₹${Number(suggested).toLocaleString('en-IN')} சேமித்தால் உங்கள் பாதுகாப்பு நிதி வேகமாக வளரும்.`
    }
    if (hasToday) {
      return `இன்று நீங்கள் ₹${Number(today).toLocaleString('en-IN')} சம்பாதித்துள்ளீர்கள். உங்கள் வழமையான வருமானத்துடன் ஒப்பிட்டு பாதுகாப்பு நிதியை வளர்க்கவும்.`
    }
    return 'இன்று வருமானம் பதிவு செய்யுங்கள். பிறகு சேமிப்பு பரிந்துரையைச் சொல்கிறோம்.'
  }

  if (medical) {
    return 'Medical stress is on your profile. Check health schemes and verified support — not a new loan.'
  }
  if (loan) return 'Loan pressure is on your profile. Review loan stacking and avoid another loan this week.'
  if (weather) return 'Weather disruption is on your profile. Stress-test your buffer in the Bad Week Simulator.'
  if (shock) return 'Income-shock focus is on. Prepare your pocket for no-work days in Bad Week Simulator.'
  if (family) return 'Family-expense focus is on. Open Goals and start saving toward that cost.'
  if (fuel) return 'Fuel-cost focus is on. Log expenses and park any small surplus.'

  if (hasToday && hasSave) {
    return `You earned ₹${Number(today).toLocaleString('en-IN')} today. Saving ₹${Number(suggested).toLocaleString('en-IN')} will grow your safety fund faster.`
  }
  if (hasToday) {
    return `You earned ₹${Number(today).toLocaleString('en-IN')} today. Compare it with your usual pay and grow your safety fund.`
  }
  return 'Log today’s income, then we can speak a clear savings nudge.'
}
